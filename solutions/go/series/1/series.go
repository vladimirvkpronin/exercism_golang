package series

// All возвращает все смежные подстроки длины n в строке s
// Пример: All(3, "49142") -> ["491", "914", "142"]
func All(n int, s string) []string {
    // Граничные случаи:
    // - если n <= 0, подстрок не существует
    // - если n > len(s), подстрок не существует
    if n <= 0 || n > len(s) {
        return []string{}
    }
    
    // Вычисляем количество возможных подстрок
    // Для строки длиной L и подстроки длиной n:
    // количество = L - n + 1
    count := len(s) - n + 1
    
    // Создаем слайс с предварительным выделением памяти
    // Это эффективнее, чем append в пустой слайс
    result := make([]string, 0, count)
    
    // Проходим по всем возможным начальным позициям
    for i := 0; i < count; i++ {
        // Извлекаем подстроку от i до i+n
        // Строки в Go иммутабельны, это создает новую строку
        result = append(result, s[i:i+n])
    }
    
    return result
}

// UnsafeFirst возвращает первую подстроку без проверок
// Может вызвать панику, если n > len(s)
func UnsafeFirst(n int, s string) string {
    // ВАЖНО: Эта функция НЕ проверяет границы
    // s[:n] вызовет панику runtime error: slice bounds out of range
    // если n > len(s)
    return s[:n]
}

// First возвращает первую подстроку с проверкой
// Возвращает подстроку и флаг, указывающий на успех
func First(n int, s string) (first string, ok bool) {
    // Проверяем возможность извлечения подстроки
    if n <= 0 || n > len(s) {
        // Возвращаем пустую строку и false
        return "", false
    }
    
    // Извлекаем подстроку и возвращаем true
    return s[:n], true
}